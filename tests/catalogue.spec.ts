import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('complete catalogue combines brand, application and search with accessible results',async({page})=>{
  await page.goto('/catalogo/');await page.getByRole('button',{name:'Continua senza tracciamento',exact:true}).click();
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(12);
  await expect(page.locator('.full-catalogue-card')).toHaveCount(49);
  await page.getByRole('button',{name:'Mostra altre famiglie',exact:true}).click();
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(24);
  await expect(page.locator('.full-catalogue-card:visible h3').nth(12)).toBeFocused();
  await page.getByLabel('Marchio',{exact:true}).selectOption('AUX');
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(4);
  await page.getByLabel('Applicazione',{exact:true}).selectOption('acqua-calda');
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(1);
  await expect(page.locator('.full-catalogue-card:visible h3')).toHaveText('Pompe di calore');
  await page.getByLabel('Cerca un prodotto o una funzione').fill('zz-inesistente');
  await expect(page.locator('.full-catalogue-empty')).toBeVisible();
  await page.getByRole('button',{name:'Mostra tutte le famiglie',exact:true}).click();
  await expect(page.getByLabel('Cerca un prodotto o una funzione')).toBeFocused();
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(12);
  await page.getByLabel('Cerca un prodotto o una funzione').fill('caldaia Beretta');
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(2);
  await page.getByLabel('Cerca un prodotto o una funzione').fill('rubinetti Fiore');
  expect(await page.locator('.full-catalogue-card:visible').count()).toBeGreaterThan(0);
  await page.locator('.full-catalogue-card:visible summary').first().click();
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();expect(audit.violations).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('catalogue links retain filters, family context and request guidance',async({page})=>{
  await page.goto('/catalogo/?marchio=Beretta&applicazione=comfort');await page.getByRole('button',{name:'Continua senza tracciamento',exact:true}).click();
  await expect(page.getByLabel('Marchio',{exact:true})).toHaveValue('Beretta');
  const card=page.locator('.full-catalogue-card').filter({has:page.getByRole('heading',{name:'Climatizzazione e terminali',exact:true})});
  await card.getByRole('link',{name:/Richiedi informazioni/}).click();
  await expect(page.locator('#request-brand')).toHaveValue('Beretta');await expect(page.locator('#request-category')).toHaveValue('Climatizzazione');
  await expect(page.locator('#request-product')).toHaveValue('Climatizzazione e terminali');
  await expect(page.locator('[data-request-guidance]')).toContainText('numero e l’uso degli ambienti');
  await page.locator('#request-message').fill('Messaggio in preparazione da conservare.');
  await page.locator('#request-category').selectOption('Termoidraulica');
  await expect(page.locator('[data-request-guidance]')).toContainText('tipo di collegamento');
  await expect(page.locator('#request-message')).toHaveValue('Messaggio in preparazione da conservare.');
  await page.goBack();await expect(page.getByLabel('Marchio',{exact:true})).toHaveValue('Beretta');
});
test('illustrated family links and range comparison connect to the full catalogue',async({page})=>{
  await page.goto('/marchi/');await page.getByRole('button',{name:'Continua senza tracciamento',exact:true}).click();
  await expect(page.locator('.brand-directory-families')).toHaveCount(9);
  await page.goto('/marchi/chaffoteaux/');
  await page.locator('.brand-range-visual').getByRole('link',{name:'Solare e accumulo',exact:true}).click();
  await expect(page).toHaveURL(/#famiglia-4$/);
  await page.getByRole('link',{name:'Tutte le famiglie nel catalogo',exact:true}).click();
  await expect(page.getByLabel('Marchio',{exact:true})).toHaveValue('Chaffoteaux');await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(5);
  await page.goto('/catalogo/?marchio=inesistente&applicazione=inesistente');
  await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(12);
});
test('catalogue remains readable and navigable without scripts',async({browser})=>{
  const context=await browser.newContext({javaScriptEnabled:false});const page=await context.newPage();
  await page.goto('/catalogo/');await expect(page.locator('.full-catalogue-card:visible')).toHaveCount(49);
  await expect(page.locator('[data-full-catalogue-tools]')).toBeHidden();
  await expect(page.locator('.full-catalogue-card a').first()).toHaveAttribute('href',/marchio=Chaffoteaux/);
  await context.close();
});
